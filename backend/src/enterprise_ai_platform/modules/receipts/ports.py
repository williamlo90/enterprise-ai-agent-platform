from typing import Protocol
from enterprise_ai_platform.modules.receipts.domain import PinBatch,PinState,TerminalEvidence,ClaimAccess,ReceiptRef,ReceiptFailure


class ReceiptRepository(Protocol):
    async def prepare(self,batch:PinBatch,payload:dict,verified_reference:dict,actor:dict)->dict: ...
    async def lookup(self,credential_hash:str,tenant_id:str,operation_id:str)->dict: ...
    async def finalise(self,credential_hash:str,settlement:dict)->dict: ...


class TerminalVerifier(Protocol):
    def verify(self,proof,batch:PinBatch)->TerminalEvidence: ...


class SettlementIssuer(Protocol):
    def issue(self,batch:PinBatch,evidence:TerminalEvidence)->dict: ...


class ClaimRelations(Protocol):
    async def access(self,context:dict,claim_id:str)->ClaimAccess: ...


class ReceiptServicePort(Protocol):
    async def prepare(self,credential:str,delegation:str,values:dict)->dict: ...
    async def finalise(self,credential:str,operation_id:str,values:dict)->dict: ...
