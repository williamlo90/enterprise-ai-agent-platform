from typing import Protocol,AsyncContextManager
from enterprise_ai_platform.modules.conversations.domain import ConversationFailure,SourceRef,SourceSubject

class SourceAccess(Protocol):
    # Implementations must pin/revalidate decisions until the enclosing owner DB
    # read commits. A cached bool or conversation ownership is not a source grant.
    def hold(self,subject:SourceSubject,sources:tuple[SourceRef,...])->AsyncContextManager[tuple[bool,...]]: ...

class ConversationRepository(Protocol):
    async def call(self,token:str,operation:str,payload:dict)->dict: ...
    async def history(self,token:str,payload:dict,sources:SourceAccess)->dict: ...
    async def run(self,operation:str,payload:dict,sources:SourceAccess)->dict: ...

class ConversationPort(Protocol):
    async def create(self,session:str,headers:dict,values:dict)->dict: ...
    async def list(self,session:str,after:str|None,limit:int)->dict: ...
    async def append(self,session:str,headers:dict,conversation_id:str,values:dict)->dict: ...
    async def assisted(self,session:str,headers:dict,conversation_id:str,values:dict)->dict: ...
    async def assisted_read(self,session:str,run_id:str)->dict: ...
    async def history(self,session:str,conversation_id:str,after:int,limit:int)->dict: ...
    async def feedback(self,session:str,headers:dict,message_id:str,values:dict)->dict: ...
