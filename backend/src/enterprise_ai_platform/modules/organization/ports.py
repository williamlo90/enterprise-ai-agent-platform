from typing import Protocol
from enterprise_ai_platform.modules.organization.domain import OrganizationFailure

class OrganizationRepository(Protocol):
    async def call(self,token:str,operation:str,payload:dict)->dict: ...

class OrganizationPort(Protocol):
    async def directory(self,session:str,*,mode:str,**filters)->dict: ...
    async def facets(self,session:str,*,mode:str,field:str,**filters)->dict: ...
    async def collections(self,session:str,*,after:str|None=None,limit:int=20)->dict: ...
    async def member(self,session:str,membership_id:str)->dict: ...
    async def replace(self,session:str,headers:dict,membership_id:str,values:dict)->dict: ...
