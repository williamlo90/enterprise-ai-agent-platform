from typing import Protocol
from enterprise_ai_platform.modules.flows.domain import FlowFailure,VerifiedTerminal


class FlowRepository(Protocol):
    async def call(self,operation:str,payload:dict)->dict: ...


class FlowTransport(Protocol):
    async def execute(self,packet:dict)->dict: ...
    async def lookup(self,packet:dict)->dict|None: ...
    async def seal(self,packet:dict)->dict: ...


class FlowProofs(Protocol):
    def verify(self,response:dict,identity:dict)->VerifiedTerminal: ...
    def settlement(self,terminal:VerifiedTerminal,identity:dict,batch:dict|None)->tuple[dict,dict|None]: ...
