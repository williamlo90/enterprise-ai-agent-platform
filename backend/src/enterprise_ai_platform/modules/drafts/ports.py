from typing import Protocol
from enterprise_ai_platform.modules.drafts.domain import DraftFailure,VerifiedDraftSource


class DraftRepository(Protocol):
    async def call(self,token:str,operation:str,payload:dict)->dict: ...


class DraftSources(Protocol):
    async def read(self,context:dict,trip_id:str,claim_id:str|None)->VerifiedDraftSource: ...


class DraftServicePort(Protocol):
    async def create(self,session,headers,values)->dict: ...
    async def read(self,session,draft_id)->dict: ...
    async def replace(self,session,headers,draft_id,values)->dict: ...
    async def preview(self,session,headers,draft_id,values)->dict: ...
