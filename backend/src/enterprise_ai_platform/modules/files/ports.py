from typing import Protocol
from enterprise_ai_platform.modules.files.domain import FileFailure, Upload


class FileRepository(Protocol):
    async def call(self,token:str|None,operation:str,payload:dict)->dict: ...
    async def claim_call(self,token:str,operation:str,payload:dict)->dict: ...


class PrivateStorage(Protocol):
    async def upload(self,key:str,data:bytes,digest:str)->str: ...
    async def recover(self,reference:dict)->str|None: ...
    async def scan(self,reference:dict)->str: ...
    async def read(self,reference:dict)->bytes: ...


class FileParser(Protocol):
    async def inspect(self,data:bytes,purpose:str,mime:str)->bool: ...


class FilesServicePort(Protocol):
    async def upload(self,session:str,headers:dict,upload:Upload)->dict: ...
    async def status(self,session:str,file_id:str)->dict: ...
    async def content(self,session:str,file_id:str)->tuple[dict,bytes]: ...
    async def claim_content(self,session:str,file_id:str,claim_id:str)->tuple[dict,bytes]: ...
