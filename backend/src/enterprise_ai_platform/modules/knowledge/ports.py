from typing import Protocol
from enterprise_ai_platform.modules.knowledge.domain import Page,KnowledgeFailure

class KnowledgeRepository(Protocol):
    async def call(self,token:str|None,operation:str,payload:dict)->dict: ...

class Extractor(Protocol):
    @property
    def ref(self)->str: ...
    async def extract(self,data:bytes,mime:str)->tuple[Page,...]: ...

class KnowledgePort(Protocol):
    async def create(self,session:str,headers:dict,values:dict)->dict: ...
    async def version(self,session:str,headers:dict,document_id:str,values:dict)->dict: ...
    async def status(self,session:str,document_id:str,version_id:str)->dict: ...
    async def mutate(self,session:str,headers:dict,operation:str,target_id:str,values:dict)->dict: ...
    async def search(self,session:str,query:str,language:str,limit:int=5)->dict: ...
    async def source(self,session:str,version_id:str)->dict: ...
    async def catalog(self,session:str,*,after:str|None=None,limit:int=20,query:str|None=None,collection:str|None=None)->dict: ...
    async def detail(self,session:str,document_id:str)->dict: ...
    async def versions(self,session:str,document_id:str,*,after:str|None=None,limit:int=20)->dict: ...
    async def preview(self,session:str,document_id:str,version_id:str)->dict: ...
    async def audience(self,session:str,document_id:str,*,after:str|None=None,limit:int=20)->dict: ...
    async def selection(self,session:str,selection_id:str,*,after:str|None=None,limit:int=20)->dict: ...
    async def create_selection(self,session:str,headers:dict,values:dict)->dict: ...
    async def replace_audience(self,session:str,headers:dict,document_id:str,values:dict)->dict: ...
